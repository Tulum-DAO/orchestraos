#!/usr/bin/env node
// Writes src/lib/emojiData.gen.ts, the full emoji picker's dataset (components/kit/EmojiPicker.tsx), from the
// unicode-emoji-json devDependency (MIT, Unicode's own emoji-test.txt as JSON). Bundled into the picker's own lazy chunk:
// the picker works offline and never fetches. Run from dashboard/:
//   node scripts/emoji-data.mjs           write the file
//   node scripts/emoji-data.mjs --check   exit 1 when the file is not what the dataset gives (a test runs this too)
// Kept: emoji up to MAX_VERSION (what current iOS, Android and desktop fonts draw), and only what the reactions API
// accepts (api/src/routes/reactions.ts isEmoji refuses letters, e.g. ℹ️). `tones` = 1 when one skin tone applies to it
// (lib/emojiPicker.ts withSkinTone): not the multi-person sequences, which take a tone per person.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

export const MAX_VERSION = 15.1;
const OUT = fileURLToPath(new URL('../src/lib/emojiData.gen.ts', import.meta.url));
const MULTI_PERSON = /‍(?:\u{1F91D}|❤|\u{1F48B})|^[\u{1F46B}-\u{1F46D}\u{1F48F}\u{1F491}]/u;

export function keep(e) {
  return Number.parseFloat(e.emoji_version) <= MAX_VERSION && !/\p{L}/u.test(e.emoji);
}

export function render(groups, version) {
  const lines = [
    `// GENERATED by scripts/emoji-data.mjs from unicode-emoji-json@${version} (MIT). Do not edit: run \`node scripts/emoji-data.mjs\`.`,
    '/** One category of the full picker: its emoji as [emoji, name, tones] (tones 1: one skin tone applies). */',
    'export interface EmojiGroup { slug: string; name: string; emojis: readonly (readonly [string, string, 0 | 1])[] }',
    '',
    'export const EMOJI_GROUPS: readonly EmojiGroup[] = [',
  ];
  for (const g of groups) {
    lines.push(`  { slug: ${JSON.stringify(g.slug)}, name: ${JSON.stringify(g.name)}, emojis: [`);
    for (const e of g.emojis.filter(keep)) {
      const tones = e.skin_tone_support && !MULTI_PERSON.test(e.emoji) ? 1 : 0;
      lines.push(`    [${JSON.stringify(e.emoji)}, ${JSON.stringify(e.name)}, ${tones}],`);
    }
    lines.push('  ] },');
  }
  lines.push('];', '');
  return lines.join('\n');
}

export function generated() {
  const require = createRequire(import.meta.url);
  const groups = require('unicode-emoji-json/data-by-group.json');
  const { version } = require('unicode-emoji-json/package.json');
  return render(groups, version);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = generated();
  if (process.argv.includes('--check')) {
    let now = '';
    try { now = readFileSync(OUT, 'utf8'); } catch { /* missing: stale */ }
    if (now !== text) { console.error('emojiData.gen.ts is stale: run node scripts/emoji-data.mjs'); process.exit(1); }
    console.log('emojiData.gen.ts is current');
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
